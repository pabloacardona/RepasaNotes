import {
  pgTable,
  uuid,
  text,
  varchar,
  integer,
  jsonb,
  timestamp,
  index,
} from "drizzle-orm/pg-core";

export type Question = {
  question: string;
  options: string[];
  correctIndex: number;
  explanation: string;
};

export const users = pgTable("users", {
  id: uuid("id").primaryKey().defaultRandom(),
  name: varchar("name", { length: 80 }).notNull(),
  email: varchar("email", { length: 160 }).notNull().unique(),
  passwordHash: text("password_hash").notNull(),
  avatar: text("avatar"), // profile picture as a small data URL (256px JPEG); null = initial letter
  mascot: varchar("mascot", { length: 24 }), // companion chosen by the player; null = a random one each visit
  createdAt: timestamp("created_at", { withTimezone: true }).defaultNow().notNull(),
});

export const notes = pgTable(
  "notes",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    userId: uuid("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    title: varchar("title", { length: 120 }).notNull(),
    topic: varchar("topic", { length: 60 }).notNull(),
    content: text("content").notNull(),
    createdAt: timestamp("created_at", { withTimezone: true }).defaultNow().notNull(),
    updatedAt: timestamp("updated_at", { withTimezone: true }).defaultNow().notNull(),
  },
  (t) => [index("notes_user_idx").on(t.userId)],
);

export const quizzes = pgTable(
  "quizzes",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    userId: uuid("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    noteId: uuid("note_id").references(() => notes.id, { onDelete: "set null" }),
    title: varchar("title", { length: 160 }).notNull(),
    topic: varchar("topic", { length: 60 }).notNull(),
    difficulty: varchar("difficulty", { length: 10 }).notNull(),
    questions: jsonb("questions").$type<Question[]>().notNull(),
    answers: jsonb("answers").$type<number[]>(),
    score: integer("score"),
    total: integer("total").notNull(),
    completedAt: timestamp("completed_at", { withTimezone: true }),
    createdAt: timestamp("created_at", { withTimezone: true }).defaultNow().notNull(),
  },
  (t) => [index("quizzes_user_idx").on(t.userId)],
);

// A quiz published through a link/QR. mode "fixed": everyone gets these questions (order shuffled per visitor).
// mode "variant": each visitor gets new questions generated by the AI from noteContent.
export const sharedQuizzes = pgTable(
  "shared_quizzes",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    userId: uuid("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    mode: varchar("mode", { length: 10 }).notNull(),
    title: varchar("title", { length: 160 }).notNull(),
    topic: varchar("topic", { length: 60 }).notNull(),
    difficulty: varchar("difficulty", { length: 10 }).notNull(),
    count: integer("count").notNull(),
    questions: jsonb("questions").$type<Question[]>().notNull(),
    noteContent: text("note_content"),
    plays: integer("plays").notNull().default(0),
    createdAt: timestamp("created_at", { withTimezone: true }).defaultNow().notNull(),
  },
  (t) => [index("shared_quizzes_user_idx").on(t.userId)],
);

export type User = typeof users.$inferSelect;
export type SharedQuiz = typeof sharedQuizzes.$inferSelect;
export type Note = typeof notes.$inferSelect;
export type Quiz = typeof quizzes.$inferSelect;
